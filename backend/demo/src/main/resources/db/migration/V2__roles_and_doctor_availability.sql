CREATE TABLE doctor_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT NOT NULL,
    day_of_week SMALLINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_doctor_availability_doctor
        FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT ck_doctor_availability_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_doctor_availability_time CHECK (start_time < end_time),
    CONSTRAINT uq_doctor_availability_slot
        UNIQUE (doctor_id, day_of_week, start_time, end_time)
);

CREATE INDEX ix_doctor_availability_doctor_day
    ON doctor_availability (doctor_id, day_of_week, start_time);