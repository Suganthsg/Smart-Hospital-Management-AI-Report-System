CREATE TABLE clinical_encounters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    appointment_id BIGINT,
    created_by_user_id BIGINT NOT NULL,
    encounter_date DATE NOT NULL,
    clinical_notes TEXT NOT NULL,
    diagnosis VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_clinical_encounters_patient FOREIGN KEY (patient_id) REFERENCES patients (id),
    CONSTRAINT fk_clinical_encounters_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id),
    CONSTRAINT fk_clinical_encounters_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id),
    CONSTRAINT fk_clinical_encounters_author FOREIGN KEY (created_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_clinical_encounters_status CHECK (status IN ('DRAFT', 'FINALIZED'))
);

CREATE INDEX ix_clinical_encounters_patient_date
    ON clinical_encounters (patient_id, encounter_date DESC);

CREATE INDEX ix_clinical_encounters_doctor_date
    ON clinical_encounters (doctor_id, encounter_date DESC);

CREATE INDEX ix_clinical_encounters_appointment
    ON clinical_encounters (appointment_id)
    WHERE appointment_id IS NOT NULL;