CREATE TABLE prescriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL,
    prescribed_by_user_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    finalized_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prescriptions_encounter FOREIGN KEY (encounter_id) REFERENCES clinical_encounters (id),
    CONSTRAINT fk_prescriptions_author FOREIGN KEY (prescribed_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_prescriptions_status CHECK (status IN ('DRAFT', 'FINALIZED')),
    CONSTRAINT ck_prescriptions_finalized CHECK (
        (status = 'DRAFT' AND finalized_at IS NULL)
        OR (status = 'FINALIZED' AND finalized_at IS NOT NULL)
    )
);

CREATE INDEX ix_prescriptions_encounter_created
    ON prescriptions (encounter_id, created_at DESC);

CREATE INDEX ix_prescriptions_author
    ON prescriptions (prescribed_by_user_id, created_at DESC);

CREATE TABLE prescription_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL,
    item_order INTEGER NOT NULL,
    medicine_name VARCHAR(200) NOT NULL,
    dosage VARCHAR(200) NOT NULL,
    route VARCHAR(100) NOT NULL,
    frequency VARCHAR(200) NOT NULL,
    duration VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL,
    instructions TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prescription_items_prescription
        FOREIGN KEY (prescription_id) REFERENCES prescriptions (id),
    CONSTRAINT ck_prescription_items_order CHECK (item_order >= 0),
    CONSTRAINT ck_prescription_items_quantity CHECK (quantity > 0),
    CONSTRAINT uq_prescription_items_order UNIQUE (prescription_id, item_order)
);

CREATE INDEX ix_prescription_items_prescription
    ON prescription_items (prescription_id, item_order);

CREATE TABLE prescription_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL,
    changed_by_user_id BIGINT NOT NULL,
    event_type VARCHAR(20) NOT NULL,
    prescription_status VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prescription_history_prescription
        FOREIGN KEY (prescription_id) REFERENCES prescriptions (id),
    CONSTRAINT fk_prescription_history_actor FOREIGN KEY (changed_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_prescription_history_event CHECK (event_type IN ('CREATED', 'UPDATED', 'FINALIZED')),
    CONSTRAINT ck_prescription_history_status CHECK (prescription_status IN ('DRAFT', 'FINALIZED'))
);

CREATE INDEX ix_prescription_history_prescription
    ON prescription_history (prescription_id, occurred_at, id);

CREATE TABLE prescription_history_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    history_id BIGINT NOT NULL,
    item_order INTEGER NOT NULL,
    medicine_name VARCHAR(200) NOT NULL,
    dosage VARCHAR(200) NOT NULL,
    route VARCHAR(100) NOT NULL,
    frequency VARCHAR(200) NOT NULL,
    duration VARCHAR(100) NOT NULL,
    quantity INTEGER NOT NULL,
    instructions TEXT,
    CONSTRAINT fk_prescription_history_items_history
        FOREIGN KEY (history_id) REFERENCES prescription_history (id),
    CONSTRAINT ck_prescription_history_items_order CHECK (item_order >= 0),
    CONSTRAINT ck_prescription_history_items_quantity CHECK (quantity > 0),
    CONSTRAINT uq_prescription_history_items_order UNIQUE (history_id, item_order)
);