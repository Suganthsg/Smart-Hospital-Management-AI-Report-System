CREATE TABLE lab_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL,
    test_name VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ORDERED',
    ordered_by_user_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lab_orders_encounter FOREIGN KEY (encounter_id) REFERENCES clinical_encounters (id),
    CONSTRAINT fk_lab_orders_author FOREIGN KEY (ordered_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_lab_orders_status CHECK (status IN ('ORDERED', 'RESULTED', 'VERIFIED', 'CANCELLED')),
    CONSTRAINT ck_lab_orders_cancelled CHECK (
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
        OR (status <> 'CANCELLED' AND cancelled_at IS NULL)
    )
);

CREATE INDEX ix_lab_orders_worklist ON lab_orders (status, created_at, id);
CREATE INDEX ix_lab_orders_encounter ON lab_orders (encounter_id, created_at DESC);

CREATE TABLE lab_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_order_id BIGINT NOT NULL,
    result_version INTEGER NOT NULL,
    result_value TEXT NOT NULL,
    units VARCHAR(100),
    reference_range VARCHAR(250),
    notes TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ENTERED',
    entered_by_user_id BIGINT NOT NULL,
    verified_by_user_id BIGINT,
    verified_at TIMESTAMPTZ,
    previous_result_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lab_results_order FOREIGN KEY (lab_order_id) REFERENCES lab_orders (id),
    CONSTRAINT fk_lab_results_entered_by FOREIGN KEY (entered_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_lab_results_verified_by FOREIGN KEY (verified_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_lab_results_previous FOREIGN KEY (previous_result_id) REFERENCES lab_results (id),
    CONSTRAINT ck_lab_results_version CHECK (result_version > 0),
    CONSTRAINT ck_lab_results_value CHECK (length(trim(result_value)) > 0),
    CONSTRAINT ck_lab_results_status CHECK (status IN ('ENTERED', 'VERIFIED')),
    CONSTRAINT ck_lab_results_verification CHECK (
        (status = 'ENTERED' AND verified_by_user_id IS NULL AND verified_at IS NULL)
        OR (status = 'VERIFIED' AND verified_by_user_id IS NOT NULL AND verified_at IS NOT NULL)
    ),
    CONSTRAINT uq_lab_results_version UNIQUE (lab_order_id, result_version),
    CONSTRAINT uq_lab_results_previous UNIQUE (previous_result_id)
);

CREATE INDEX ix_lab_results_order_version ON lab_results (lab_order_id, result_version DESC);