CREATE TABLE medical_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL,
    author_user_id BIGINT NOT NULL,
    reviewer_user_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    generation_mode VARCHAR(20) NOT NULL DEFAULT 'MOCK',
    content TEXT NOT NULL,
    submitted_at TIMESTAMPTZ,
    reviewed_at TIMESTAMPTZ,
    reviewer_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_medical_reports_encounter FOREIGN KEY (encounter_id) REFERENCES clinical_encounters (id),
    CONSTRAINT fk_medical_reports_author FOREIGN KEY (author_user_id) REFERENCES users (id),
    CONSTRAINT fk_medical_reports_reviewer FOREIGN KEY (reviewer_user_id) REFERENCES users (id),
    CONSTRAINT ck_medical_reports_status CHECK (status IN ('DRAFT', 'IN_REVIEW', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_medical_reports_generation_mode CHECK (generation_mode IN ('MOCK', 'EXTERNAL')),
    CONSTRAINT ck_medical_reports_submission CHECK (
        (status = 'DRAFT' AND submitted_at IS NULL)
        OR (status <> 'DRAFT' AND submitted_at IS NOT NULL)
    ),
    CONSTRAINT ck_medical_reports_review CHECK (
        (status IN ('APPROVED', 'REJECTED') AND reviewer_user_id IS NOT NULL AND reviewed_at IS NOT NULL)
        OR (status IN ('DRAFT', 'IN_REVIEW') AND reviewer_user_id IS NULL AND reviewed_at IS NULL)
    )
);

CREATE INDEX ix_medical_reports_encounter_created
    ON medical_reports (encounter_id, created_at DESC);

CREATE INDEX ix_medical_reports_status_submitted
    ON medical_reports (status, submitted_at);

CREATE INDEX ix_medical_reports_author_created
    ON medical_reports (author_user_id, created_at DESC);

CREATE TABLE medical_report_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    event_type VARCHAR(20) NOT NULL,
    report_status VARCHAR(20) NOT NULL,
    content_snapshot TEXT NOT NULL,
    event_note TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_medical_report_history_report FOREIGN KEY (report_id) REFERENCES medical_reports (id),
    CONSTRAINT fk_medical_report_history_actor FOREIGN KEY (actor_user_id) REFERENCES users (id),
    CONSTRAINT ck_medical_report_history_event CHECK (
        event_type IN ('GENERATED', 'EDITED', 'SUBMITTED', 'APPROVED', 'REJECTED')
    ),
    CONSTRAINT ck_medical_report_history_status CHECK (
        report_status IN ('DRAFT', 'IN_REVIEW', 'APPROVED', 'REJECTED')
    )
);

CREATE INDEX ix_medical_report_history_report
    ON medical_report_history (report_id, occurred_at, id);